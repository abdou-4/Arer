"""R0: the frozen detection baseline.

The remediation plan (R0, task 1) requires a fixed regression corpus with
expected scores, levels and finding IDs, stored OUTSIDE the runtime output
folders and NOT regenerated automatically during ordinary tests. This file
is that corpus: four deterministic mails, with the full rule-engine outcome
(score, level, exit code, finding IDs, per-category points) frozen below as
plain assertions. A change here means detection changed, and per the plan
that needs its own measured, separately justified commit - never a silent
workflow fix.

intel and history are skipped on purpose: intel depends on feed freshness
(a time/environment-dependent "feeds stale" notice with weight 0) and
history depends on the user's own database. The baseline freezes the rule
engine itself, not the environment.

To re-baseline deliberately: run this file, compare old vs new values,
document the before/after comparison, and update the frozen dict in the
same commit.
"""
from email.message import EmailMessage
from pathlib import Path

import pytest

from arer.config import load_config
from arer.loader import load_any
from arer.models import Level
from arer.pipeline import run_pipeline

SKIP = {"intel", "history"}

# ---- deterministic corpus (byte-identical on every machine) ---------------- #

SALAD = ("<html><noframes><xml><CZVVGQPYUH><QWERTYUIOP><ASDFGHJKL><!DOCTYPE><!DOCTYPE>"
         "<!DOCTYPE><!DOCTYPE>"
         + "<textarea></textarea>" * 25 + "<option>" * 10
         + '<div style="display:none !important;">x</div>' * 22
         + '<a><div style="background: url(\'https://img.example.net/p.jpg\'); '
           'width:640px;height:1138px"></div></a>')
RAW_PHISH = ("From: news@discord.com\r\nTo: v@example.com\r\nSubject: win\r\n"
             "MIME-Version: 1.0\r\nContent-Type: text/html; charset=utf-8\r\n\r\n" + SALAD)


def _paypal_eml() -> bytes:
    m = EmailMessage()
    m["From"] = '"PayPal Support" <support@paypa1-secure.com>'
    m["To"] = "victim@corp.com"
    m["Reply-To"] = "collector@evil.example"
    m["Subject"] = "Verify now"
    m.set_content("Go to http://1.2.3.4/login")
    m.add_attachment(b"MZ\x90\x00" + b"\0" * 50, maintype="application",
                     subtype="octet-stream", filename="invoice.pdf.exe")
    return m.as_bytes()


def _clean_eml() -> bytes:
    m = EmailMessage()
    m["From"] = "Sam <sam@example.org>"
    m["To"] = "me@example.org"
    m["Subject"] = "Lunch"
    m["Date"] = "Mon, 05 Jan 2026 09:00:00 +0000"
    m["Message-ID"] = "<1@example.org>"
    m.set_content("Hi, lunch on Friday?")
    return m.as_bytes()


def _partial_eml() -> bytes:
    m = EmailMessage()
    m["Subject"] = "?"
    m.set_content("hello")
    return m.as_bytes()


# ---- the frozen baseline (never regenerated by the test run) --------------- #

BASELINE = {
    "phish_raw.eml": {
        "score": 20, "level": Level.SUSPICIOUS, "exit": 3,
        "findings": ["auth.results_missing", "body.html_obfuscation",
                     "headers.missing_date", "headers.missing_received"],
        "by_category": {"auth": 5, "body": 8, "headers": 7},
    },
    "phish_paypal.eml": {
        "score": 74, "level": Level.MALICIOUS, "exit": 5,
        "findings": ["attachment.double_extension", "attachment.executable",
                     "auth.results_missing", "headers.missing_date",
                     "headers.missing_received", "sender.lookalike_domain",
                     "sender.reply_to_mismatch", "url.ip_host"],
        "by_category": {"attachment": 25, "auth": 5, "headers": 7, "sender": 27, "url": 10},
    },
    "clean.eml": {
        "score": 10, "level": Level.CLEAN, "exit": 0,
        "findings": ["auth.results_missing", "headers.missing_received"],
        "by_category": {"auth": 5, "headers": 5},
    },
    "partial.eml": {
        "score": 22, "level": Level.SUSPICIOUS, "exit": 3,
        "findings": ["auth.results_missing", "headers.missing_date",
                     "headers.missing_received", "sender.invalid_format"],
        "by_category": {"auth": 5, "headers": 7, "sender": 10},
    },
}

BYTES_OF = {"phish_raw.eml": RAW_PHISH.encode(), "phish_paypal.eml": _paypal_eml(),
            "clean.eml": _clean_eml(), "partial.eml": _partial_eml()}


@pytest.fixture(scope="module")
def verdicts(tmp_path_factory):
    cfg = load_config()
    d = tmp_path_factory.mktemp("baseline")
    out = {}
    for name, blob in BYTES_OF.items():
        p = d / name
        p.write_bytes(blob)
        out[name] = run_pipeline(load_any(p, cfg), cfg, skip=SKIP)
    return out


@pytest.mark.parametrize("name", sorted(BASELINE))
def test_baseline_score_level_and_exit(verdicts, name):
    want = BASELINE[name]
    v = verdicts[name]
    assert v.score == want["score"], f"{name}: score drifted from the frozen baseline"
    assert v.level == want["level"], f"{name}: level drifted from the frozen baseline"
    from arer.exitcodes import EXIT_CODES
    assert EXIT_CODES[v.level] == want["exit"]


@pytest.mark.parametrize("name", sorted(BASELINE))
def test_baseline_finding_ids(verdicts, name):
    want = BASELINE[name]
    got = sorted(f.id for f in verdicts[name].findings)
    assert got == want["findings"], f"{name}: finding IDs drifted from the frozen baseline"


@pytest.mark.parametrize("name", sorted(BASELINE))
def test_baseline_category_points(verdicts, name):
    want = BASELINE[name]
    got = {c: p for c, p in verdicts[name].by_category.items() if p}
    assert got == want["by_category"], f"{name}: category points drifted from the frozen baseline"
